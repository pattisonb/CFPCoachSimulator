const n = (v: number) => v.toLocaleString("en-US");
const ordinal = (k: number) => {
  const s = k % 100 >= 11 && k % 100 <= 13 ? "th" : (["th", "st", "nd", "rd"][k % 10] ?? "th");
  return `${k}${s}`;
};

