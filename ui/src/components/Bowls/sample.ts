/** The sample with you in it: your team takes SMU's place in the Holiday Bowl (unless you're already in the lineup). */
export function sampleFor(team: string, teamName: string): BowlProjection {
  const there = SEEDS.some((x) => x[4] === team || x[6] === team);
  const bowls = SAMPLE.bowls.map((b) => (there || b.away !== "smu" ? b : { ...b, away: team, away_name: teamName }));
  return { ...SAMPLE, bowls: bowls.map((b) => ({ ...b, mine: b.away === team || b.home === team })) };
}

