#!/usr/bin/env node
/**
 * Copies the face art into the package: art/manifest.json (made by tools/build_faces.py build), slimmed to
 * what the compositor reads, as
 *   faces.json        the data, for fetch() or any language
 *   src/data.ts       the same, as a module (import data from "pocket-faces/data")
 *   face.schema.json  a JSON Schema for a player's face JSON, every id listed
 * Run after any change to the art: `npm run sync` here, or `npm run faces:pack` at the repo root.
 */
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL("../", import.meta.url);
const pkg = JSON.parse(readFileSync(new URL("package.json", here), "utf8"));
const m = JSON.parse(readFileSync(new URL("../../art/manifest.json", here), "utf8"));

// what the compositor and a customiser read; the art's file paths, measurements and fitting notes stay behind
const grid = (g) => ({ pixels: g.pixels });
const info = (p) => Object.fromEntries(["label", "random", "asymmetric", "fade", "widthClass"].filter((k) => k in p).map((k) => [k, p[k]]));
const parts = {};
for (const [cat, list] of Object.entries(m.parts)) {
  parts[cat] = list.map((p) =>
    "variants" in p
      ? { id: p.id, ...info(p), variants: Object.fromEntries(Object.entries(p.variants).map(([f, g]) => [f, grid(g)])) }
      : { id: p.id, ...info(p), ...grid(p) });
}
const rest = { ...m };
delete rest._doc;
const data = { version: pkg.version, ...rest, parts };

writeFileSync(new URL("faces.json", here), JSON.stringify(data) + "\n");
writeFileSync(new URL("src/data.ts", here),
  `// GENERATED by scripts/sync.mjs from the face art: don't edit.\nimport type { Manifest } from "./types.ts";\n\n` +
  `const data: Manifest = JSON.parse(${JSON.stringify(JSON.stringify(data))});\nexport default data;\n`);

const ids = (cat) => (m.parts[cat] ?? []).map((p) => p.id);
const one = (list, nullable, description) => ({ description, ...(nullable ? { enum: [null, ...list] } : { enum: list }) });
const partProps = Object.fromEntries(m.order.filter((c) => c !== "face_shape" && ids(c).length).map((c) => {
  const k = m.categories[c];
  const first = k.default ? `left out: ${ids(c)[0]}` : "left out: none";
  return [k.field, one(ids(c), k.optional, `${k.label}${k.optional ? "; null: none" : ""} (${first})`)];
}));
const flippable = m.order.filter((c) => m.categories[c].flip);
const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: `pocket-faces/${pkg.version}/face.schema.json`,
  title: "A pocket-faces face",
  description: "A player's look: one id per field (null: none). Made by createFaces().random(id) or resolve(spec).",
  type: "object",
  required: ["faceShape", "skinTone", "hairColor"],
  properties: {
    faceShape: one(ids("face_shape"), false, "the head (its width picks the hair, beard and ears to fit it)"),
    skinTone: one(m.skinTones.map((t) => t.id), false, "skin and its shadow"),
    hairColor: one(m.hairColors.map((h) => h.id), false, "the hair, facial hair and brow colour"),
    eyeColor: one(m.eyeColors.map((e) => e.id), false, `the iris colour (left out: ${m.eyeColors[0].id})`),
    ...partProps,
    hairFade: { type: "boolean", description: "a faded style's temples in the lighter stroke (only styles with a fade change; left out: false)" },
    flip: { type: "array", uniqueItems: true, items: { enum: flippable }, description: "layers drawn mirrored (only asymmetric parts change; left out: none)" },
  },
};
writeFileSync(new URL("face.schema.json", here), JSON.stringify(schema, null, 2) + "\n");
console.log(`pocket-faces ${pkg.version}: faces.json ${(JSON.stringify(data).length / 1024).toFixed(0)} KB, ` +
  Object.entries(parts).filter(([, l]) => l.length).map(([c, l]) => `${l.length} ${c}`).join(", "));
