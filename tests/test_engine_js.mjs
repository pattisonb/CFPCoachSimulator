test("random: the same draws from the same seed", () => {
  // every draw the engine's methods make, 400 a seed in turn, then the seed set again (seed + 3)
  // (a gauss or gammavariate draw goes through a logarithm, a sine or a cosine, which JavaScript and the C library
  // Python uses may round one place apart: such a draw is counted, not failed, as the Python test counted it; the
  // generator's own numbers under it are exact either way)
  const near = (e, g) => typeof g === "number" && Math.abs(e - g) < 1e-12 * Math.max(1, Math.abs(e));
  const bad = [];
  let n = 0, ulp = 0;
  for (const { seed, first, kinds, gauss, gamma, tail } of EXPECTED.rng) {
    const r = new Random(seed), got = [];
    for (let i = 0; i < 400; i++) {
      const k = i % 9;
      if (k === 0) got.push(r.random());
      else if (k === 1) got.push(r.randint(1, 6 + i));
      else if (k === 2) got.push(r.gauss(3.5, 2.25));
      else if (k === 3) got.push(r.choices(range(7), { weights: [0.1, 2, 3.3, 0.7, 5, 1e-3, 2.2] })[0]);
      else if (k === 4) got.push(r.choice(range(11)));
      else if (k === 5) got.push(r.uniform(-3, 9.5));
      else if (k === 6) got.push(r.gammavariate(2.2 + (i % 5) * 0.4, 1.7));
      else if (k === 7) got.push(r.choices(range(5), { k: 3 }));
      else got.push(r.randint(-40, 1000000));
    }
    r.seed(seed + 3);
    const end = [r.gauss(0, 1), r.gammavariate(0.6, 2.0), r.gammavariate(1.0, 2.0)];
    n += got.length + end.length;
    const draws = (k) => got.filter((_, i) => i % 9 === k);
    const float = (what, e, g) => { if (same(e, g)) return; if (near(e, g)) ulp++; else bad.push(`seed ${seed}, ${what}: ${g}, Python ${e}`); };
    first.forEach((e, i) => { if (i !== 2 && i !== 6 && !same(e, got[i])) bad.push(`seed ${seed} draw ${i} (${KINDS[i]}): ${JSON.stringify(got[i])}, Python ${JSON.stringify(e)}`); });
    kinds.forEach((e, k) => { if (e === null) return; const d = digest(draws(k)); if (d !== e) bad.push(`seed ${seed}, the ${KINDS[k]} draws: digest ${d}, Python ${e}`); });
    equal([draws(2).length, draws(6).length], [gauss.length, gamma.length]);
    gauss.forEach((e, i) => float(`gauss draw ${i}`, e, draws(2)[i]));
    gamma.forEach((e, i) => float(`gammavariate draw ${i}`, e, draws(6)[i]));
    tail.forEach((e, i) => float(`set again, draw ${i}`, e, end[i]));
  }
  assert(!bad.length, "pyrt.js is not Python's random:\n" + bad.slice(0, 12).join("\n"));
  summary.push(`rng: ${n} draws, 0 wrong, ${ulp} off in the last place`);
});

