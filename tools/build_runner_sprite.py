"""Build web/runner.js, the little ball carrier who runs at the front of the sim bar.

Reads tools/sprites/ball-carrier-run.png (four 48 x 48 frames side by side, the ball carrier's run in a
red kit, from the pocket-franchise sprite work) and writes it out as one SVG of pixel paths, one path per
color. The kit's reds become CSS classes whose fill is the team's primary color (and a darker shade of
it), so the runner wears whatever team the season is for; every other color (outline, skin, facemask,
ball, white pants) stays as drawn.

Needs Pillow (a build tool only; the game itself loads the generated web/runner.js):
    python3 tools/build_runner_sprite.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "sprites" / "ball-carrier-run.png"
OUT = ROOT / "web" / "runner.js"
FRAME = 48

# the art's kit reds -> a team part; anything else keeps its own color
KIT = {
    (172, 50, 50): "kit",        # jersey, helmet, socks
    (75, 17, 17): "kit-shade",   # their shading
    (105, 30, 30): "kit-shade",
}


def main() -> None:
    im = Image.open(SRC).convert("RGBA")
    w, h = im.size
    assert h == FRAME and w % FRAME == 0, f"{SRC.name}: expected 48 px tall frames side by side, got {w} x {h}"
    px = im.load()
    # one path per color: each row's runs of the same color become "M x y h n v 1 h -n z"
    runs: dict[str, list[str]] = {}
    for y in range(h):
        x = 0
        while x < w:
            r, g, b, a = px[x, y]
            if a < 128:
                x += 1
                continue
            key = KIT.get((r, g, b)) or "#%02x%02x%02x" % (r, g, b)
            n = 1
            # a run stops at a frame edge, so each frame's pixels stay in their own 48 px cell
            while x + n < w and (x + n) % FRAME and px[x + n, y][3] >= 128 and (KIT.get(px[x + n, y][:3]) or "#%02x%02x%02x" % px[x + n, y][:3]) == key:
                n += 1
            runs.setdefault(key, []).append(f"M{x} {y}h{n}v1h-{n}z")
            x += n
    paths = []
    for key in sorted(runs, key=lambda k: (k.startswith("#"), k)):
        d = "".join(runs[key])
        paths.append(f'<path class="runner-{key}" d="{d}"/>' if not key.startswith("#") else f'<path fill="{key}" d="{d}"/>')
    svg = (f'<svg class="runner-sheet" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
           f'shape-rendering="crispEdges" aria-hidden="true" focusable="false">{"".join(paths)}</svg>')
    frames = w // FRAME
    js = f"""/* The little ball carrier who runs at the front of the sim bar, in the team's colors.
   GENERATED by tools/build_runner_sprite.py from tools/sprites/ball-carrier-run.png; do not edit by hand.
   {frames} frames of {FRAME} x {FRAME} px side by side; styles.css (.runner) steps through them and paints the
   kit (.runner-kit, .runner-kit-shade) in --team-primary. */
(function () {{
  const SHEET = '{svg}';
  // the runner: a {FRAME} px window onto the sheet, set at the leading edge of a progress bar
  function runner() {{
    const span = document.createElement("span");
    span.className = "runner";
    span.setAttribute("aria-hidden", "true");
    span.innerHTML = SHEET;
    return span;
  }}
  // the sim bars (a week's in the header, a longer sim's in the overlay) each get one
  for (const id of ["sim-bar", "season-progress-bar"]) {{
    const bar = document.getElementById(id);
    if (!bar || bar.querySelector(".runner")) continue;
    bar.append(runner());
    bar.parentElement.classList.add("has-runner");
  }}
  window.CFPRunner = runner;
}})();
"""
    OUT.write_text(js)
    print(f"wrote {OUT.relative_to(ROOT)}: {frames} frames, {len(runs)} colors, {len(js) // 1024} KB")


if __name__ == "__main__":
    main()
