"""Clear the generated data that piles up under data/ (nothing tracked by git is touched).

    python tools/clean_data.py              # show what would go and how much it weighs
    python tools/clean_data.py --yes        # remove it
    python tools/clean_data.py --yes --saves   # also remove every saved season and its box scores

What goes by default:
- data/leagues/*.json whose career has no save in data/seasons (a career's league teams file is
  rebuilt on demand by league.ensure_built, so even a live one is safe to drop; orphans never are
  rebuilt and were the bulk: test runs delete their seasons but left these behind)
- data/seasons/<id>/ box-score folders whose season file is gone
- data/long_run/ outputs (tools/long_run.py writes them again), data/analysis/, data/coaches/
- data/player_ratings.json (tools/export_ratings.py writes it again)
- the browser site dist/ and the precomputed base league data/base_league.json and
  data/base_meta.json (tools/build_site.py writes all three again)
- every __pycache__ under the project
Kept: source data (cfb_sim_data/, data/ballots, data/recruiting, data/market), the built
data/engine_teams.json and data/player_potential.json, and your saves unless --saves.
"""
from __future__ import annotations
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEASONS, LEAGUES = ROOT / "data" / "seasons", ROOT / "data" / "leagues"


def size(p: Path) -> int:
    return sum(f.stat().st_size for f in p.rglob("*") if f.is_file()) if p.is_dir() else p.stat().st_size


def plan(saves_too: bool) -> list[tuple[str, Path]]:
    out: list[tuple[str, Path]] = []
    live = {p.stem for p in SEASONS.glob("*.json")} if SEASONS.exists() else set()
    if LEAGUES.exists():
        for p in LEAGUES.glob("*.json"):
            if re.sub(r"-\d{4}$", "", p.stem) not in live or saves_too:
                out.append(("league file without a saved season" if not saves_too else "league file", p))
    if SEASONS.exists():
        for d in SEASONS.iterdir():
            if d.is_dir() and (d.name not in live or saves_too):
                out.append(("box scores without a season file" if not saves_too else "box scores", d))
            elif saves_too and d.suffix == ".json":
                out.append(("saved season", d))
    for name in ("long_run", "analysis", "coaches"):
        d = ROOT / "data" / name
        if d.exists():
            out.append((f"data/{name} output", d))
    ratings = ROOT / "data" / "player_ratings.json"
    if ratings.exists():
        out.append(("export (regenerated by tools/export_ratings.py)", ratings))
    for p in (ROOT / "dist", ROOT / "data" / "base_league.json", ROOT / "data" / "base_meta.json"):
        if p.exists():
            out.append(("site build (regenerated by tools/build_site.py)", p))
    for d in ROOT.rglob("__pycache__"):
        if ".git" not in d.parts and ".claude" not in d.parts:
            out.append(("__pycache__", d))
    return out


if __name__ == "__main__":
    yes, saves_too = "--yes" in sys.argv, "--saves" in sys.argv
    items = plan(saves_too)
    total = 0
    by_kind: dict[str, tuple[int, int]] = {}
    for kind, p in items:
        s = size(p)
        total += s
        n, b = by_kind.get(kind, (0, 0))
        by_kind[kind] = (n + 1, b + s)
    for kind, (n, b) in sorted(by_kind.items(), key=lambda kv: -kv[1][1]):
        print(f"{b / 1e6:9.1f} MB  {n:4d}  {kind}")
    print(f"{total / 1e6:9.1f} MB  total {'removed' if yes else 'would go (add --yes to remove)'}")
    if yes:
        for _, p in items:
            shutil.rmtree(p, ignore_errors=True) if p.is_dir() else p.unlink(missing_ok=True)
