"""Rasterize the US state outlines (web/us-states.js: Albers USA, Census boundaries) into a pixel grid for the new
UI's map (ui/src/components/TileMap/usPixels.ts). Each cell takes the state its center falls in; a state too small to
own a cell (RI, DE, DC) still gets the one under its center. Run it again only to change the grid's size:

    python3 tools/pixel_map.py [cols]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "us-states.js"
OUT = ROOT / "ui" / "src" / "components" / "TileMap" / "usPixels.ts"
COLS = int(sys.argv[1]) if len(sys.argv) > 1 else 72   # *tune* the grid's width in cells; rows follow the map's shape


def polygons(d: str) -> list[list[tuple[float, float]]]:
    """An SVG path of M/L/Z commands as closed rings."""
    rings, ring = [], []
    for cmd, xs, ys in re.findall(r"([MLZ])(?:(-?[\d.]+),(-?[\d.]+))?", d):
        if cmd == "M":
            if ring:
                rings.append(ring)
            ring = [(float(xs), float(ys))]
        elif cmd == "L":
            ring.append((float(xs), float(ys)))
        elif cmd == "Z" and ring:
            rings.append(ring)
            ring = []
    if ring:
        rings.append(ring)
    return rings


def inside(x: float, y: float, rings) -> bool:
    """Even-odd: a point inside an odd number of a state's rings (holes and islands both work)."""
    hit = False
    for ring in rings:
        n = len(ring)
        for i in range(n):
            x1, y1 = ring[i]
            x2, y2 = ring[(i + 1) % n]
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
                hit = not hit
    return hit


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    data = json.loads(text[text.index("{"): text.rindex("}") + 1].replace("viewBox:", '"viewBox":').replace("paths:", '"paths":'))
    _, _, width, height = (float(v) for v in data["viewBox"].split())
    states = {k: polygons(v) for k, v in data["paths"].items()}
    boxes = {k: (min(x for r in rs for x, _ in r), min(y for r in rs for _, y in r),
                 max(x for r in rs for x, _ in r), max(y for r in rs for _, y in r)) for k, rs in states.items()}
    cell = width / COLS
    rows = round(height / cell)
    grid = [[".."] * COLS for _ in range(rows)]
    for r in range(rows):
        for c in range(COLS):
            x, y = (c + 0.5) * cell, (r + 0.5) * cell
            for k, rs in states.items():
                x0, y0, x1, y1 = boxes[k]
                if x0 <= x <= x1 and y0 <= y <= y1 and inside(x, y, rs):
                    grid[r][c] = k
                    break
    # a state too small for a cell of its own takes the one under its center
    have = {k for row in grid for k in row}
    for k, (x0, y0, x1, y1) in boxes.items():
        if k not in have:
            grid[min(rows - 1, int((y0 + y1) / 2 / cell))][min(COLS - 1, int((x0 + x1) / 2 / cell))] = k
    # cropped to the cells the map uses
    used = [(r, c) for r in range(rows) for c in range(COLS) if grid[r][c] != ".."]
    r0, r1 = min(r for r, _ in used), max(r for r, _ in used)
    c0, c1 = min(c for _, c in used), max(c for _, c in used)
    grid = [row[c0:c1 + 1] for row in grid[r0:r1 + 1]]
    rows, cols = len(grid), c1 - c0 + 1
    lines = ",\n".join(f'  "{"".join(row)}"' for row in grid)
    OUT.write_text(
        "// Generated by tools/pixel_map.py from web/us-states.js (Albers USA, US Census boundaries). Do not edit by\n"
        "// hand: run the script again. Each row is two letters a cell, the state its center falls in (\"..\" is none).\n"
        f"export const PIXEL_COLS = {cols};\n"
        f"export const PIXEL_ROWS = {rows};\n"
        f"export const PIXEL_ROWS_DATA: string[] = [\n{lines},\n];\n",
        encoding="utf-8",
    )
    print(f"{cols} x {rows} cells, {len({k for row in grid for k in row} - {'..'})} states -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
