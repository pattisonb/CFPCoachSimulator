"""Build web/us-states.js from us-atlas states-10m.json (TopoJSON, lon/lat degrees).

Usage: python tools/make_us_map.py path/to/states-10m.json

Source: us-atlas@3.0.1 (ISC license), built from US Census Bureau cartographic boundary data.
Each ring is projected with an Albers USA composite (a port of d3-geo's geoAlbersUsa for a
975 x 610 canvas); web/us-map.js implements the same projection for dots.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
K = 1070.0
DROP = {"60", "66", "69", "72", "78"}
FIPS = {
    "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC",
    "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
    "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT",
    "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
    "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT",
    "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY",
}


def conic(parallels, rotate, center, scale, translate):
    """Conic equal area projector: (lat, lon) degrees -> (x, y) screen."""
    p0, p1 = math.radians(parallels[0]), math.radians(parallels[1])
    n = (math.sin(p0) + math.sin(p1)) / 2
    c = math.cos(p0) ** 2 + 2 * n * math.sin(p0)
    r0 = math.sqrt(c) / n

    def raw(lam, phi):
        r = math.sqrt(c - 2 * n * math.sin(phi)) / n
        return r * math.sin(n * lam), r0 - r * math.cos(n * lam)

    cx, cy = raw(math.radians(center[0]), math.radians(center[1]))

    def project(lat, lon):
        x, y = raw(math.radians(lon + rotate), math.radians(lat))
        return translate[0] + scale * (x - cx), translate[1] - scale * (y - cy)
    return project


LOWER48 = conic((29.5, 45.5), 96, (-0.6, 38.7), K, (487.5, 305))
ALASKA = conic((55, 65), 154, (-2, 58.5), 0.35 * K, (487.5 - 0.307 * K, 305 + 0.201 * K))
HAWAII = conic((8, 18), 157, (-3, 19.9), K, (487.5 - 0.205 * K, 305 + 0.212 * K))


def albers_usa(lat, lon):
    if 18 <= lat <= 23 and -161 <= lon <= -154:
        return HAWAII(lat, lon)
    if lat >= 50 and lon < -129:   # d3 uses a box to -129 so the panhandle stays in Alaska
        return ALASKA(lat, lon)
    return LOWER48(lat, lon)


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    out = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        out.append(pts)
    return out


def ring_points(arcs, indexes):
    pts = []
    for i in indexes:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def build(topo):
    arcs = decode_arcs(topo)
    paths = {}
    for g in topo["objects"]["states"]["geometries"]:
        fips = str(g["id"]).zfill(2)
        if fips in DROP:
            continue
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        d = []
        for poly in polys:
            for ring in poly:
                # the Aleutians cross the antimeridian (lon > 0): wrap them west so Alaska stays one piece
                pts = [albers_usa(lat, lon - 360 if fips == "02" and lon > 0 else lon) for lon, lat in ring_points(arcs, ring)]
                seg, last = [], None
                for x, y in pts:
                    q = (round(x, 1), round(y, 1))
                    if q != last:
                        seg.append(q)
                    last = q
                if len(seg) > 1 and seg[0] == seg[-1]:
                    seg.pop()
                if len(seg) < 3:
                    continue
                d.append("M" + "L".join(f"{x:g},{y:g}" for x, y in seg) + "Z")
        paths[FIPS[fips]] = "".join(d)
    return paths


def main(src):
    topo = json.loads(Path(src).read_text())
    paths = build(topo)
    assert len(paths) == 51, len(paths)
    body = json.dumps(paths, sort_keys=True, separators=(",", ":"))
    header = ("// US state outlines in a 975 x 610 Albers USA canvas (lower 48 plus Alaska and Hawaii insets).\n"
              "// Generated by tools/make_us_map.py from us-atlas@3.0.1 states-10m.json (ISC license;\n"
              "// US Census Bureau cartographic boundary data). Do not edit by hand.\n")
    out = ROOT / "web" / "us-states.js"
    out.write_text(header + 'window.US_STATES = {viewBox: "0 0 975 610", paths: ' + body + "};\n")
    print(f"wrote {out} ({out.stat().st_size} bytes, {len(paths)} states)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
